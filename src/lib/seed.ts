// Dynamic helpers to ensure demo dates are perpetually current regardless of when the presentation runs
export const getSeedDate = (offsetDays: number = 0): string => {
  const d = new Date();
  d.setDate(d.getDate() + offsetDays);
  const dayNum = d.toLocaleDateString("en-IN", { day: "2-digit" });
  const month = d.toLocaleDateString("en-IN", { month: "short" });
  return `${dayNum} ${month} ${d.getFullYear()}`;
};

export const getSeedIso = (hours: number, minutes: number, offsetDays: number = 0): string => {
  const d = new Date();
  d.setDate(d.getDate() + offsetDays);
  d.setHours(hours, minutes, 0, 0);
  return d.toISOString();
};

